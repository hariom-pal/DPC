<?php

declare(strict_types=1);

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\Config;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;
use Throwable;

/**
 * The evidence-table database grants, as a command rather than a runbook
 * (**TD-1**).
 *
 * **Why this is a command.** The control it applies is not code — it is a
 * `GRANT` on a production database — and for most of the project it lived in a
 * markdown runbook. A runbook has two failure modes that matter here. It gets
 * archived, and then the control is a paragraph nobody runs; and it goes stale
 * silently — the one written in M5 named **two** tables, and by M9 there were
 * **twelve**, because a document cannot notice a migration. Deriving the SQL from
 * `config/dpc.php` closes both: the table list is the same list
 * `EvidenceGrantsTest` checks against every model that guards itself, so it
 * cannot fall behind the schema without the build going red.
 *
 * **What it does not do.** It does not run `GRANT` for you. Applying it needs a
 * privileged account that the application deliberately does not have, and a
 * command that could widen its own privileges would be a worse problem than the
 * one it solves. It prints the statements; a DBA runs them.
 *
 * **`--verify` is the half worth running repeatedly.** It attempts each write
 * the control is supposed to refuse, as whichever user the application is
 * actually connecting as, and reports what happened. That is the only way to
 * find out that a grant was widened by an unrelated change six months after
 * deployment — which the original runbook asked for in prose and had no way to
 * check.
 *
 * The probes are safe by construction: every statement carries `WHERE id = -1`,
 * so no row can match. MySQL checks privileges before it matches rows, so a
 * refusal still proves the grant is right, and a success proves it is wrong
 * without touching a single record.
 */
class EvidenceGrantsCommand extends Command
{
    protected $signature = 'security:evidence-grants
        {--user=odpc_app : The application database user the grants apply to}
        {--host=% : The host part of the MySQL account}
        {--database= : Schema name to qualify the statements with (defaults to the connection'."'".'s)}
        {--connection= : Connection to read the schema from (defaults to the default connection)}
        {--verify : Instead of printing SQL, attempt each forbidden write and report what the database did}';

    protected $description = 'Print (or verify) the database grants that make the evidence tables immutable (TD-1)';

    public function handle(): int
    {
        $tables = $this->evidenceTables();

        if ($tables === []) {
            $this->components->error('No evidence tables are configured under `dpc.security.evidence_tables`.');

            return self::FAILURE;
        }

        return $this->option('verify')
            ? $this->verify($tables)
            : $this->print($tables);
    }

    /**
     * @param  array<string, array{update: list<string>}>  $tables
     */
    private function print(array $tables): int
    {
        $user = (string) $this->option('user');
        $host = (string) $this->option('host');
        $account = "'{$user}'@'{$host}'";
        $schema = $this->schema();

        $this->line('-- e-DPC Portal — evidence-table permissions (TD-1).');
        $this->line('-- Generated by `php artisan security:evidence-grants`. Run as a privileged account.');
        $this->line('--');
        $this->line('-- The application user keeps SELECT and INSERT on every evidence table, and loses');
        $this->line('-- DELETE outright. UPDATE is granted per column where the record has a lifecycle,');
        $this->line('-- and withheld entirely where it has none. Revoking UPDATE outright instead would');
        $this->line('-- stop every calculation from completing — see the note on dpc_calculation_runs.');
        $this->newLine();

        foreach ($tables as $table => $rules) {
            $qualified = $schema === null ? "`{$table}`" : "`{$schema}`.`{$table}`";
            $columns = $rules['update'];

            $this->line("-- {$table}");
            $this->line("REVOKE UPDATE, DELETE ON {$qualified} FROM {$account};");
            $this->line("GRANT SELECT, INSERT ON {$qualified} TO {$account};");

            if ($columns === []) {
                $this->line('-- No UPDATE at all: rows here are written once and never transition.');
            } else {
                $this->line(sprintf(
                    'GRANT UPDATE (%s) ON %s TO %s;',
                    implode(', ', array_map(static fn (string $c): string => "`{$c}`", $columns)),
                    $qualified,
                    $account,
                ));
                $this->line('-- Only the lifecycle columns. Everything else is fixed once written.');
            }

            $this->newLine();
        }

        $this->line('FLUSH PRIVILEGES;');
        $this->newLine();
        $this->components->info(sprintf(
            '%d evidence tables. Re-run with --verify against the application account after applying.',
            count($tables),
        ));

        return self::SUCCESS;
    }

    /**
     * Attempt each write the grants are supposed to refuse.
     *
     * @param  array<string, array{update: list<string>}>  $tables
     */
    private function verify(array $tables): int
    {
        $connection = DB::connection($this->option('connection') === null ? null : (string) $this->option('connection'));

        if ($connection->getDriverName() !== 'mysql') {
            // Said plainly rather than skipped: a check that quietly passes on
            // the wrong engine reports a green that means nothing. SQLite has no
            // grant system at all, so there is nothing here it could verify.
            $this->components->error(sprintf(
                'Grants are a MySQL control and this connection is `%s`. Nothing was verified.',
                $connection->getDriverName(),
            ));

            return self::FAILURE;
        }

        $this->components->info(sprintf(
            'Probing as `%s` on `%s`. Every statement matches no rows (WHERE id = -1), so nothing can be changed.',
            (string) $connection->selectOne('SELECT CURRENT_USER() AS u')->u,
            $connection->getDatabaseName(),
        ));
        $this->newLine();

        $rows = [];
        $failures = 0;

        foreach ($tables as $table => $rules) {
            if (! Schema::connection($connection->getName())->hasTable($table)) {
                $rows[] = [$table, '—', 'table absent', '⚠ skipped'];
                $failures++;

                continue;
            }

            // DELETE must always be refused.
            [$refused, $detail] = $this->probe(
                fn () => $connection->statement("DELETE FROM `{$table}` WHERE id = -1"),
            );
            $rows[] = [$table, 'DELETE', $refused ? 'refused' : 'PERMITTED', $refused ? '✓' : '✗ '.$detail];
            $failures += $refused ? 0 : 1;

            // UPDATE of a column the lifecycle does not need must be refused.
            $forbidden = $this->aForbiddenColumn($connection->getName(), $table, $rules['update']);

            if ($forbidden === null) {
                $rows[] = [$table, 'UPDATE (any)', 'every column is a lifecycle column', '— nothing to probe'];
            } else {
                [$refused, $detail] = $this->probe(
                    fn () => $connection->statement("UPDATE `{$table}` SET `{$forbidden}` = `{$forbidden}` WHERE id = -1"),
                );
                $rows[] = [$table, "UPDATE ({$forbidden})", $refused ? 'refused' : 'PERMITTED', $refused ? '✓' : '✗ '.$detail];
                $failures += $refused ? 0 : 1;
            }

            // And a column the lifecycle DOES need must still work, or the
            // grant is too tight and the application is broken.
            if ($rules['update'] !== []) {
                $column = $rules['update'][0];
                [$refused] = $this->probe(
                    fn () => $connection->statement("UPDATE `{$table}` SET `{$column}` = `{$column}` WHERE id = -1"),
                );
                $rows[] = [$table, "UPDATE ({$column})", $refused ? 'REFUSED' : 'permitted', $refused ? '✗ too tight' : '✓'];
                $failures += $refused ? 1 : 0;
            }
        }

        $this->table(['Table', 'Statement', 'Database said', 'Verdict'], $rows);

        if ($failures > 0) {
            $this->components->error(sprintf(
                '%d probe(s) came back wrong. The evidence tables are not protected as TD-1 requires.',
                $failures,
            ));

            return self::FAILURE;
        }

        $this->components->info('Every evidence table refuses what it should and permits what it must.');

        return self::SUCCESS;
    }

    /**
     * Run a statement and report whether the database refused it.
     *
     * @param  callable(): mixed  $statement
     * @return array{0: bool, 1: string}
     */
    private function probe(callable $statement): array
    {
        try {
            $statement();

            return [false, ''];
        } catch (Throwable $e) {
            // Any refusal counts. Distinguishing 1142 (no privilege) from other
            // errors would be more precise and less useful: a statement the
            // database will not execute is a statement nobody can tamper with.
            return [true, substr($e->getMessage(), 0, 60)];
        }
    }

    /**
     * A real column on the table that the lifecycle does not need — the one to
     * probe. `null` when every column is permitted, which needs no probe.
     *
     * @param  list<string>  $permitted
     */
    private function aForbiddenColumn(string $connection, string $table, array $permitted): ?string
    {
        foreach (Schema::connection($connection)->getColumnListing($table) as $column) {
            if ($column !== 'id' && ! in_array($column, $permitted, true)) {
                return $column;
            }
        }

        return null;
    }

    /**
     * @return array<string, array{update: list<string>}>
     */
    private function evidenceTables(): array
    {
        /** @var array<string, array{update: list<string>}> $tables */
        $tables = Config::get('dpc.security.evidence_tables', []);

        return $tables;
    }

    private function schema(): ?string
    {
        $explicit = $this->option('database');

        if (is_string($explicit) && $explicit !== '') {
            return $explicit;
        }

        $name = DB::connection($this->option('connection') === null ? null : (string) $this->option('connection'))
            ->getDatabaseName();

        // An SQLite connection's "database" is a file path, which has no place
        // in a GRANT. Better to emit unqualified statements a DBA must qualify
        // than a qualified one that is wrong.
        return str_contains($name, '/') || $name === ':memory:' ? null : $name;
    }
}
